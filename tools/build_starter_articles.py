"""Turns the Poradnik articles (prototyp/src/articles/*.txt) into starter posts for the plugin.

Usage: python3 tools/build_starter_articles.py
Writes wp-content/plugins/remontuj24-core/demo/articles.php with block markup the
starter importer inserts as posts.
"""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "prototyp" / "src" / "articles"
OUT = ROOT / "wp-content" / "plugins" / "remontuj24-core" / "demo" / "articles.php"

# SEO titles the client supplied with the articles (20.10.2026).
SEO_TITLES = {
    "7-bledow-przy-wykanczaniu-mieszkania": "7 błędów przy wykańczaniu mieszkania | Remontuj24",
    "ile-kosztuje-wykonczenie-mieszkania": "Ile kosztuje wykończenie mieszkania pod klucz? | Remontuj24",
}
# Publication order: the newest article is shown large on the Poradnik page.
DATES = {
    "mieszkanie-od-dewelopera-co-dalej": "2026-10-20 13:22:00",
    "ile-kosztuje-wykonczenie-mieszkania": "2026-10-20 13:46:00",
    "7-bledow-przy-wykanczaniu-mieszkania": "2026-10-20 15:11:00",
}


def block(name, inner, attrs=None):
    a = " " + json.dumps(attrs, ensure_ascii=False, separators=(",", ":")) if attrs else ""
    return f"<!-- wp:{name}{a} -->\n{inner}\n<!-- /wp:{name} -->"


def php_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


posts = []
for f in sorted(SRC.glob("*.txt")):
    head, body = f.read_text(encoding="utf-8").split("\n---\n", 1)
    meta = dict(line.split(": ", 1) for line in head.splitlines())
    blocks = []
    for i, line in enumerate(l for l in body.splitlines() if l.strip()):
        text = html.escape(line[3:] if line.startswith("## ") else line[2:] if line.startswith("> ") else line, quote=False)
        if line.startswith("## "):
            blocks.append(block("heading", f'<h2 class="wp-block-heading">{text}</h2>'))
        elif line.startswith("> "):
            blocks.append(block("paragraph", f'<p class="signoff">{text}</p>', {"className": "signoff"}))
        elif i == 0:
            blocks.append(block("paragraph", f'<p class="lead">{text}</p>', {"className": "lead"}))
        else:
            blocks.append(block("paragraph", f"<p>{text}</p>"))
    posts.append({
        "slug": f.stem,
        "title": meta["title"],
        "category": meta["category"],
        "date": DATES.get(f.stem, "2026-10-20 12:00:00"),
        "image": meta["image"] + "-1600",
        "excerpt": meta["excerpt"],
        "seo_title": SEO_TITLES.get(f.stem, ""),
        "seo_desc": meta["description"],
        "content": "\n\n".join(blocks),
    })

lines = ["<?php", "// Generated by tools/build_starter_articles.py — edit the source articles, not this file.", "return ["]
for p in posts:
    lines.append("\t[")
    for k, v in p.items():
        lines.append(f"\t\t{php_str(k)} => {php_str(v)},")
    lines.append("\t],")
lines.append("];")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT, len(posts), "articles")
